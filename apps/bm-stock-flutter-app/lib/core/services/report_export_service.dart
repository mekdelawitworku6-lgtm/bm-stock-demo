import 'dart:convert';
import 'dart:typed_data';
import 'package:csv/csv.dart';
import 'package:excel/excel.dart';
import 'package:flutter/material.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'file_download.dart' as fd;

class ReportSection {
  final String title;
  final List<String> columns;
  final List<List<Object?>> rows;
  const ReportSection({
    required this.title,
    required this.columns,
    required this.rows,
  });
}

class ReportExportService {
  static const _blue = PdfColor.fromInt(0xFF025EA7);
  static const _ink = PdfColor.fromInt(0xFF0F172A);
  static const _slate = PdfColor.fromInt(0xFF64748B);
  static const _border = PdfColor.fromInt(0xFFE2E8F0);

  /// Builds the file bytes (TEXT/CSV or PDF) for a set of sections.
  static Uint8List buildCsv(String title, List<ReportSection> sections) {
    final buffer = StringBuffer();
    buffer.writeln('# ${_csvEscape(title)}');
    buffer.writeln('# ${DateTime.now().toIso8601String().substring(0, 16)}');
    buffer.writeln();
    for (final section in sections) {
      buffer.writeln('## ${_csvEscape(section.title)}');
      final rows = <List<dynamic>>[
        section.columns,
        ...section.rows.map((r) => r.map(_csvValue).toList()),
      ];
      buffer.writeln(const ListToCsvConverter(eol: '\n').convert(rows));
      buffer.writeln();
    }
    return Uint8List.fromList(utf8.encode(buffer.toString()));
  }

  static Uint8List buildExcel(String title, List<ReportSection> sections) {
    final excel = Excel.createExcel();
    final defaultSheet = excel.getDefaultSheet();
    if (defaultSheet != null) excel.delete(defaultSheet);

    for (final section in sections) {
      final sheetName = section.title.length > 31 ? section.title.substring(0, 31) : section.title;
      final sheet = excel[sheetName];
      sheet.appendRow([TextCellValue(title)]);
      sheet.appendRow([TextCellValue(DateTime.now().toIso8601String().substring(0, 16))]);
      sheet.appendRow([]);
      sheet.appendRow(section.columns.map((c) => TextCellValue(c)).toList());
      for (final row in section.rows) {
        sheet.appendRow(row.map((c) => TextCellValue(_str(c))).toList());
      }
    }

    final bytes = excel.encode();
    return Uint8List.fromList(bytes ?? []);
  }

  static Future<Uint8List> buildPdf(BuildContext context, String title, List<ReportSection> sections, {bool blueHeader = true}) async {
    final doc = pw.Document();
    doc.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(32),
        footer: (pw.Context ctx) => pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.start,
          mainAxisSize: pw.MainAxisSize.min,
          children: [
            pw.Divider(color: _border),
            pw.SizedBox(height: 4),
            pw.Row(
              mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
              children: [
                pw.Text(
                  'Generated by BM Stock',
                  style: const pw.TextStyle(fontSize: 8, color: _slate),
                ),
                pw.Text(
                  'Page ${ctx.pageNumber} of ${ctx.pagesCount}',
                  style: const pw.TextStyle(fontSize: 8, color: _slate),
                ),
              ],
            ),
          ],
        ),
        build: (pw.Context ctx) => <pw.Widget>[
          pw.Row(
            mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
            crossAxisAlignment: pw.CrossAxisAlignment.end,
            children: [
              pw.Expanded(
                child: pw.Text(_sanitizeForPdf(title), style: pw.TextStyle(fontSize: 20, fontWeight: pw.FontWeight.bold, color: _ink)),
              ),
              pw.Text(
                _formatTimestamp(DateTime.now()),
                style: const pw.TextStyle(fontSize: 9, color: _slate),
              ),
            ],
          ),
          pw.SizedBox(height: 6),
          if (blueHeader) ...[
            pw.Container(height: 2, color: _blue),
          ],
          pw.SizedBox(height: 16),
          ...sections.map(
            (s) => pw.Column(
              crossAxisAlignment: pw.CrossAxisAlignment.start,
              children: [
                pw.Text(
                  _sanitizeForPdf(s.title),
                  style: pw.TextStyle(
                      fontSize: 13,
                      fontWeight: pw.FontWeight.bold,
                      color: blueHeader ? _blue : _ink),
                ),
                pw.SizedBox(height: 8),
                pw.TableHelper.fromTextArray(
                  headers: s.columns.map(_sanitizeForPdf).toList(),
                  data: s.rows.map((r) => r.map(_str).toList()).toList(),
                  headerStyle: pw.TextStyle(
                      fontSize: 8,
                      fontWeight: pw.FontWeight.bold,
                      color: blueHeader ? PdfColors.white : _ink),
                  headerDecoration: pw.BoxDecoration(
                      color: blueHeader ? _blue : PdfColor.fromInt(0xFFF1F5F9)),
                  cellStyle: const pw.TextStyle(fontSize: 8, color: _ink),
                  cellAlignments: Map<int, pw.Alignment>.fromIterables(
                    List.generate(s.columns.length, (i) => i),
                    List.generate(
                      s.columns.length,
                      (_) => pw.Alignment.centerLeft,
                    ),
                  ),
                  border: pw.TableBorder.all(color: _border, width: 0.5),
                  oddRowDecoration: const pw.BoxDecoration(color: PdfColor.fromInt(0xFFF8FAFC)),
                  rowDecoration: const pw.BoxDecoration(),
                ),
                pw.SizedBox(height: 18),
              ],
            ),
          ),
        ],
      ),
    );
    return doc.save();
  }

  /// Downloads [bytes] to the device Downloads folder (mobile/desktop)
  /// or triggers a browser download (web).
  static Future<bool> downloadBytes(Uint8List bytes, String filename) async {
    if (bytes.isEmpty) return false;
    return fd.downloadBytes(bytes, filename, _mime(filename));
  }

  /// Writes [bytes] to a temp file and opens the system share sheet (mobile/desktop)
  /// or triggers a Web Share (web).
  static Future<bool> shareBytes(Uint8List bytes, String filename) async {
    if (bytes.isEmpty) return false;
    return fd.shareBytes(bytes, filename, _mime(filename));
  }

  /// Opens [bytes] for preview in the system PDF viewer (mobile/desktop)
  /// or in a new browser tab (web).
  static Future<bool> previewBytes(Uint8List bytes, String filename) async {
    if (bytes.isEmpty) return false;
    return fd.previewBytes(bytes, filename, _mime(filename));
  }

  static String _mime(String filename) {
    final ext = filename.split('.').last.toLowerCase();
    if (ext == 'pdf') return 'application/pdf';
    if (ext == 'xlsx') return 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet';
    return 'text/csv';
  }

  static String _formatTimestamp(DateTime dt) {
    return '${dt.year}-${dt.month.toString().padLeft(2, '0')}-${dt.day.toString().padLeft(2, '0')} '
        '${dt.hour.toString().padLeft(2, '0')}:${dt.minute.toString().padLeft(2, '0')}';
  }

  static String _sanitizeForPdf(String text) {
    return text
        .replaceAll('⇄', '<->')
        .replaceAll('→', '->')
        .replaceAll('←', '<-')
        .replaceAll('—', '-')
        .replaceAll('–', '-')
        .replaceAll('−', '-')
        .replaceAll('•', '*')
        .replaceAll('“', '"')
        .replaceAll('”', '"')
        .replaceAll('‘', "'")
        .replaceAll('’', "'");
  }

  static String _csvValue(Object? v) => v?.toString() ?? '';
  static String _str(Object? v) => _sanitizeForPdf(v?.toString() ?? '');
  static String _csvEscape(String v) => '"${v.replaceAll('"', '""')}"';
}