import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { UserRole } from '@/common/enums';

export class EmployeeResponseDto {
  @ApiProperty({ description: 'Unique identifier' })
  id: string;

  @ApiProperty({ description: 'Employee name' })
  name: string;

  @ApiProperty({ description: 'Phone number' })
  phoneNumber: string;

  @ApiProperty({ description: 'Base commission rate' })
  baseCommissionRate: number;

  @ApiPropertyOptional({ description: 'Base commission type: percent or fixed' })
  baseCommissionType?: string;

  @ApiProperty({ description: 'Total sales amount generated by employee' })
  salesAmount: number;

  @ApiProperty({ description: 'Job title' })
  jobTitle?: string;

  @ApiProperty({ description: 'User role', enum: UserRole })
  role?: UserRole;

  @ApiProperty({ description: 'Linked user ID' })
  userId?: string;

  @ApiProperty({ description: 'User FullName' })
  userFullName: string;

  @ApiProperty({ description: 'Shop name' })
  shopName: string;

  @ApiProperty({ description: 'Warehouse name' })
  warehouseName: string;

  @ApiPropertyOptional({ description: 'Shop ID' })
  shopId?: string;

  @ApiPropertyOptional({ description: 'Warehouse ID' })
  warehouseId?: string;

  @ApiPropertyOptional({ description: 'Staff login method' })
  authMethod?: 'password' | 'pin';

  @ApiPropertyOptional({ description: 'Assigned login password (admin reference)' })
  assignedPassword?: string;

  @ApiPropertyOptional({ description: 'Assigned login PIN (admin reference)' })
  assignedPin?: string;

  @ApiProperty({ description: 'Employee permissions' })
  permissions?: Record<string, any>;

  @ApiPropertyOptional({ description: 'Company ID' })
  companyId?: string;

  @ApiPropertyOptional({ description: 'Branch and store access permissions' })
  branchPermissions?: Record<string, any>;

  @ApiPropertyOptional({ description: 'Whether this employee is the company owner/creator' })
  isOwner?: boolean;

  @ApiProperty({ description: 'Creation date' })
  createdAt: Date;

  @ApiProperty({ description: 'Last updated date' })
  updatedAt: Date;
}